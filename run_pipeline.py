def main():
    ap = argparse.ArgumentParser(description="Synthetic IoT sensor-to-cloud pipeline demo")
    ap.add_argument("--loss", type=float, default=0.10, help="wireless link loss rate")
    ap.add_argument("--nodes", type=int, default=3, help="sensor nodes")
    ap.add_argument("--readings", type=int, default=240, help="readings per node (main run)")
    ap.add_argument("--seed", type=int, default=7, help="RNG seed (reproducible)")
    args = ap.parse_args()

    os.makedirs(RESULTS, exist_ok=True)

    # 1. Mock cloud.
    cloud = CloudServer(jsonl_path=os.path.join(RESULTS, "cloud_readings.jsonl")).start()
    print(f"[cloud] mock ingest API at {cloud.url}")

    link_kwargs = dict(loss_rate=args.loss, corrupt_rate=0.02,
                       latency_mean_ms=120.0, latency_std_ms=45.0)
    sender_kwargs = dict(max_retries=3, base_backoff_s=0.4)

    # 2. Main run -> cloud.
    print(f"[sim] main run: {args.nodes} nodes x {args.readings} readings, "
          f"loss={args.loss:.0%}")
    generated, gateway, samples = run_simulation(
        args.nodes, args.readings, link_kwargs, sender_kwargs,
        cloud_url=cloud.url, seed=args.seed, collect_samples=True,
    )
    summary = metrics.summarize_run(generated, gateway)
    print(f"[sim] delivered {summary['accepted_unique']}/{summary['generated']} "
          f"({summary['delivery_rate']:.1%}), cloud stored: {cloud.reading_count()}")

    # 3. Loss sweep (smaller, no cloud — analysis only).
    sweep_losses = [0.0, 0.05, 0.10, 0.20, 0.30]
    sweep = []
    for lr in sweep_losses:
        lk = dict(link_kwargs); lk["loss_rate"] = lr
        gen, gw, _ = run_simulation(3, 80, lk, sender_kwargs,
                                    cloud_url=None, seed=args.seed)
        dr = metrics.delivery_rate(gen, gw.accepted)
        sweep.append((lr, dr))
        print(f"[sweep] loss={lr:.0%} -> delivery={dr:.1%}")

    # 4. Plots.
    p_delivery = os.path.join(RESULTS, "delivery_vs_loss.png")
    p_latency = os.path.join(RESULTS, "latency_cdf.png")
    p_outcomes = os.path.join(RESULTS, "gateway_outcomes.png")
    p_series = os.path.join(RESULTS, "sample_timeseries.png")
    plots.plot_delivery_vs_loss([s[0] for s in sweep], [s[1] for s in sweep], p_delivery)
    plots.plot_latency_cdf(gateway.latencies_s, p_latency)
    plots.plot_gateway_outcomes(gateway.stats(), p_outcomes)
    plots.plot_sample_timeseries(samples, p_series)
    print("[plots] wrote 4 charts to results/")

    # 5. Summary + dashboard.
    with open(os.path.join(RESULTS, "summary.json"), "w") as f:
        json.dump({"run": summary, "sweep": sweep,
                   "gateway": gateway.stats()}, f, indent=2)
    build_dashboard(
        summary, sweep, gateway.stats(),
        [("Delivery vs loss", b64img(p_delivery)),
         ("Latency CDF", b64img(p_latency)),
         ("Gateway outcomes", b64img(p_outcomes)),
         ("Sample sensor stream", b64img(p_series))],
        os.path.join(RESULTS, "dashboard.html"),
    )
    # Also copy dashboard to project root for easy opening.
    with open(os.path.join(RESULTS, "dashboard.html")) as src:
        with open(os.path.join(HERE, "dashboard.html"), "w") as dst:
            dst.write(src.read())

    cloud.stop()
    print("[done] results/ + dashboard.html ready. "
          f"Delivery rate: {summary['delivery_rate']:.1%} (simulated).")


if __name__ == "__main__":
    main()
