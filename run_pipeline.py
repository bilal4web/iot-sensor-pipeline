#!/usr/bin/env python3
"""
One-command end-to-end demo of the SYNTHETIC IoT sensor-to-cloud pipeline.

    python3 run_pipeline.py [--loss 0.1] [--nodes 3] [--readings 240] [--seed 7]

What it does:
  1. Starts the mock cloud ingest server (localhost HTTP).
  2. Runs synthetic sensor nodes -> lossy wireless link (with ARQ retries)
     -> gateway (CRC check, dedup, batching) -> cloud.
  3. Sweeps several link-loss rates and measures delivery rate.
  4. Writes plots + dashboard.html + results/summary.json.

Everything is simulated; no real hardware, network, or CISNR data involved.
"""

import argparse
import base64
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from sensors.node import SensorNode, make_packet, serialize
from wireless.link import WirelessLink, ReliableSender
from gateway.aggregator import Gateway
from cloud.ingest import CloudServer
from analysis import metrics, plots

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")


def run_simulation(num_nodes, readings_per_node, link_kwargs, sender_kwargs,
                   cloud_url=None, seed=7, interval_s=5.0, batch_size=20,
                   collect_samples=False):
    """Run one full synthetic pipeline pass. Returns (generated, gateway, samples)."""
    nodes = [SensorNode(f"node-{i}", seed=seed + i, interval_s=interval_s)
             for i in range(num_nodes)]
    link = WirelessLink(seed=seed, **link_kwargs)
    sender = ReliableSender(link, **sender_kwargs)
    gateway = Gateway(cloud_url=cloud_url, batch_size=batch_size)

    generated = 0
    samples = []
    for node in nodes:
        for seq in range(readings_per_node):
            t = seq * interval_s + hash(node.node_id) % 3  # small per-node offset
            reading = node.generate_reading(seq, float(t))
            if collect_samples and node.node_id == "node-0":
                samples.append(reading)
            packet = make_packet(reading)
            raw = serialize(packet)
            sender.send(raw, float(t), gateway.receive)
            generated += 1
    gateway.flush()
    return generated, gateway, samples


def b64img(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode()


